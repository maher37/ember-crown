// npm run balance [-- --runs 500 --only f7-sunken-shrine --report]
// Plays every fight many times with a bot party at its expected level and prints win rates.
import { writeFileSync } from 'node:fs';
import { roadFights, simulate, storyFights, target, type SimResult } from '../src/sim/simulate';
import { SIM_PARTIES } from '../src/sim/party';

const args = process.argv.slice(2);
const arg = (name: string) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? args[i + 1] : undefined;
};
const runs = Number(arg('runs') ?? 500);
const only = arg('only');
const writeReport = args.includes('--report');
const pct = (x: number) => `${Math.round(x * 100)}%`;

const fights = [...storyFights(), ...roadFights()].filter(
  (e) => !only || e.id === only || e.code === only,
);
const rows: SimResult[] = [];
const start = Date.now();
for (const e of fights) {
  for (const party of Object.keys(SIM_PARTIES)) {
    for (const difficulty of ['easy', 'medium', 'hard'] as const) {
      const r = simulate(e.id, {
        runs: difficulty === 'medium' ? runs : Math.ceil(runs / 2),
        party,
        difficulty,
      });
      rows.push(r);
    }
  }
  const med = rows.filter((r) => r.encounterId === e.id && r.difficulty === 'medium');
  const [lo, hi] = target(e.id);
  const flag = med.some((r) => r.winRate < lo)
    ? ' ▼ too hard'
    : med.some((r) => r.winRate > hi)
      ? ' ▲ easy'
      : '';
  console.log(
    `${e.code.padEnd(5)} L${e.expectedLevel} ${e.name.padEnd(40)} medium ${med.map((r) => pct(r.winRate).padStart(4)).join(' / ')}  target ${pct(lo)}–${pct(hi)}${flag}`,
  );
  for (const r of rows.filter((x) => x.encounterId === e.id && (x.errors.length || x.stuck)))
    console.log(
      `   ! ${r.party} ${r.difficulty}: ${r.stuck} stuck, errors: ${r.errors.join(' | ')}`,
    );
}
console.log(`\n${rows.length} batches in ${Math.round((Date.now() - start) / 1000)} s`);

if (writeReport) {
  const lines = [
    '# Balance report',
    '',
    `Generated by \`npm run balance -- --report\` (${runs} runs per fight on Medium, ${Math.ceil(runs / 2)} on Easy and Hard), with a bot party at each fight's expected level and full resources (one fight at a time).`,
    '',
    'Parties: ' +
      Object.entries(SIM_PARTIES)
        .map(([id, p]) => `**${id}** (${p.label})`)
        .join('; ') +
      '.',
    '',
    'Targets [inferred, RPG_Game_Plan §5]: main fights won 85–97% on Medium at the expected level; Hard-designed fights 75–95%; elites 40–85% (they are Deadly by design); travel encounters 90%+. The bot plays sensibly but not brilliantly, so real players should do a little better.',
    '',
    '| Fight | Lvl | Party | Easy | Medium | Hard | Medium: rounds | HP left (wins) | Downed | A hero died | Target |',
    '|---|---|---|---|---|---|---|---|---|---|---|',
  ];
  for (const e of fights)
    for (const party of Object.keys(SIM_PARTIES)) {
      const by = (d: string) =>
        rows.find((r) => r.encounterId === e.id && r.party === party && r.difficulty === d)!;
      const m = by('medium');
      const [lo, hi] = target(e.id);
      const mark = m.winRate < lo ? ' ▼' : m.winRate > hi ? ' ▲' : '';
      lines.push(
        `| ${e.code} ${e.name} | ${m.level} | ${party} | ${pct(by('easy').winRate)} | **${pct(m.winRate)}**${mark} | ${pct(by('hard').winRate)} | ${m.avgRounds.toFixed(1)} | ${pct(m.hpLeft)} | ${m.downed.toFixed(2)} | ${pct(m.deathRate)} | ${pct(lo)}–${pct(hi)} |`,
      );
    }
  writeFileSync('docs/Balance_Report.md', lines.join('\n') + '\n');
  console.log('Wrote docs/Balance_Report.md');
}
