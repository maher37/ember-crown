import { dataFiles } from './files';

interface Flagged {
  file: string;
  /** e.g. "monsters › goblin" or "classes › bard › resources › bardic-inspiration". */
  where: string;
  note: string;
}

/** Every record flagged `"verify": true`, walking all data files. */
export function collectVerifyFlags(): Flagged[] {
  const out: Flagged[] = [];
  const walk = (node: unknown, file: string, trail: string[]) => {
    if (Array.isArray(node)) {
      node.forEach((x) => walk(x, file, trail));
      return;
    }
    if (!node || typeof node !== 'object') return;
    const obj = node as Record<string, unknown>;
    const label =
      typeof obj.name === 'string' ? obj.name : typeof obj.id === 'string' ? obj.id : null;
    const here = label ? [...trail, label] : trail;
    if (obj.verify === true) {
      out.push({
        file,
        where: here.join(' › ') || '(whole file)',
        note: String(obj.verifyNote ?? ''),
      });
    }
    for (const [k, v] of Object.entries(obj))
      if (typeof v === 'object')
        walk(v, file, label ? here : [...trail, k].filter((x) => !/^\d+$/.test(x)));
  };
  for (const f of dataFiles) walk(f.raw, f.name, []);
  return out;
}

/** The markdown checklist committed as docs/Data_Verify_Checklist.md. */
export function verifyChecklistMarkdown(): string {
  const flags = collectVerifyFlags();
  const lines = [
    '# Data verify checklist',
    '',
    '*Generated by `npm run verify-list` from the `"verify": true` flags in `src/data/`. Do not edit by hand.*',
    '',
    'Each line was entered from memory or is marked ⚠ in the design docs. Check it against your PDFs. When a line is right (or fixed), remove its `verify` and `verifyNote` from the JSON and run `npm run verify-list` again.',
    '',
    `**${flags.length} items to check.**`,
  ];
  let current = '';
  for (const f of flags) {
    if (f.file !== current) {
      current = f.file;
      lines.push('', `## ${f.file}`, '');
    }
    lines.push(`- [ ] **${f.where}**: ${f.note}`);
  }
  return lines.join('\n') + '\n';
}
